# 오인됐다. "그럴 수가 있나요?" / "할 수가 없나요?" 가 주제 있는 질문으로 통과해,
# 맥락 없이 그대로 검색됐다. 한국어에서 극히 흔한 구문이다.
#
# 판정 기준은 **앞 글자의 받침이 ㄹ 인가** — 할/그럴/볼/될 처럼 관형사형 어미다.
# `수가는`, `진료수가`, `초진료 수가` 처럼 가격을 뜻하는 쓰임은 건드리지 않는다.
_AUX_SU_RE = re.compile(r"([가-힣])\s*수\s*(?=가|있|없|도|는|밖)")


def _strip_auxiliary_su(text: str) -> str:
    """보조용언으로 쓰인 "수" 를 지운다 (주제어 `수가` 오인 방지)."""

    def _repl(m: "re.Match[str]") -> str:
        ch = m.group(1)
        code = ord(ch) - 0xAC00
        # 한글 음절의 종성 index 8 = ㄹ
        if 0 <= code <= 11171 and code % 28 == 8:
            return ch + " "
        return m.group(0)

    return _AUX_SU_RE.sub(_repl, text)


# ── 맥락 없이는 뜻이 정해지지 않는 "내용 없는 요청·확인" 어절 ─────────────────
#
# 3차 검수 P1-4 — 주제 없는 조각 판정이 **2어절 이하**에만 걸려서, 조사·어미를 붙여
# 3어절만 만들면 규칙이 무력화됐다. 실측 미탐:
#   "더 자세히 알려주세요" / "조금 더 쉽게 설명해주세요" / "둘 다 가능한가요?" /
#   "그냥 하면 안 되나요?"
# 이들은 **내용어(명사)가 하나도 없고** 요청·확인 표현만으로 이뤄진다. 앞 대화 없이는
# 무엇을 더 설명해야 하는지 알 수 없으므로 길이와 무관하게 되묻는 것이 맞다.
#
# 반대로 "하얀색으로 하면 어떻게 되나요?" 처럼 **내용어가 있는** 질문은 여기서 잡지
# 않는다 — 보험청구 주제가 아니어도 첫 질문으로 들어왔을 때와 동일하게 처리하는 것이
# 일관적이다(§13 남은 위험 참고). 사전에 없는 어휘를 쓴 정상 질문을 막지 않기 위함이다.
