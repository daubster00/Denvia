def _is_context_free_request(words: list[str]) -> bool:
    """내용어가 하나도 없고 요청·확인 표현만으로 이뤄진 질문인가 (3차 검수 P1-4).

    어절이 **전부** 맥락 의존 일반어면 True. 주제어가 없을 때만 의미가 있으므로
    호출부에서 그 조건을 먼저 확인한다.
    """
    if not words:
        return False
    return all(_strip_marks(w) in _CONTEXT_FREE_WORDS for w in words)


def _words(question: str) -> list[str]:
    """어절 목록. 기호만 남는 토막은 세지 않는다."""
    return [w for w in question.split() if w.strip("?!.…,·\"'()[]")]


def _strip_marks(word: str) -> str:
    return word.strip("?!.…,·\"'()[]~-")


def has_anaphora(question: str) -> bool:
    """앞 대화를 받는 말(그럼/그건/그 경우/그렇게…)이 섞여 있는가."""
    words = _words(question)
    for idx, raw in enumerate(words):
        word = _strip_marks(raw)
        if word.startswith(_ANAPHORA_PREFIXES):
            return True
        if word.startswith(_ANAPHORA_GLUED):
            return True
        if word in _ANAPHORA_DETERMINERS and idx + 1 < len(words):
            nxt = _strip_marks(words[idx + 1])
            if nxt.startswith(_ANAPHORA_HEADS):
                return True
    return False


def has_clinical_latin_token(question: str) -> bool:
    """치과 현장에서 쓰는 영문 약어가 섞여 있는가 (2026-11-04).

    데스크·진료 스태프는 ``CU`` ``RP`` ``PRR`` ``GI`` ``Endo`` ``NiTi`` ``CT`` 처럼
    영문 약어를 일상적으로 쓴다. 한글 사전으로는 이런 질문의 주제를 영영 잡을 수 없고,
    보강 전 실측에서 ``"PRR 이 뭔가요"`` ``"엔도중에 NiTi 는 몇 번 넣을수 있지?"``
    같은 정상 질문이 통째로 되묻기로 떨어졌다.

    두 글자 이상의 라틴 문자 토막이 있으면 도메인 질문으로 본다. 잡담에는 거의 없고,
    있더라도 흔한 영어 기능어는 제외한다.
    """
    for token in _LATIN_TOKEN_RE.findall(question):
        if token.lower() not in _LATIN_STOPWORDS:
            return True
    return False


def has_clinical_suffix(question: str) -> bool:
    """의학용어 접미사(~술 / ~염 / ~증)로 끝나는 어절이 있는가 (2026-11-04).

    ``피판작성술`` ``국소피판술`` ``급성치관주위염`` 처럼 사전에 일일이 올릴 수 없는
    전문용어를 잡는다. 실측에서 사전 누락 오탐의 상당수가 이 형태였다.
    """
    for raw in _words(question):
        word = _strip_marks(raw)
        if len(word) < _CLINICAL_SUFFIX_MIN_LEN:
            continue
        # 조사가 붙은 형태("~술로", "~염이", "~증으로")도 잡되, 꼬리는 최대 3글자만
        # 떼어 본다. 제한 없이 훑으면 긴 일상어의 중간이 우연히 걸린다.
        for drop in range(0, 4):
            stem = word[: len(word) - drop] if drop else word
            if len(stem) < _CLINICAL_SUFFIX_MIN_LEN:
                break
            if stem.endswith(_CLINICAL_SUFFIXES):
                return True
    return False


def has_billing_topic(question: str) -> bool:
    """질문에 보험청구 주제어가 있는가 (웹 통합 계층 사전).

    공백을 지운 문장에서도 찾는다 — "초진료산정기준알려주세요" 처럼 붙여 쓴 질문도
    주제가 있는 질문으로 보기 위함. 영문 약어도 주제로 인정한다.
    """
    if not question:
        return False
    if has_clinical_latin_token(question):
        return True
    if has_clinical_suffix(question):
        return True
    # 3차 검수 P1-3 — "~ㄹ 수가" 보조용언을 먼저 걷어낸다(주제어 `수가` 오인 방지).
    cleaned = _strip_auxiliary_su(question)
    glued = re.sub(r"\s+", "", cleaned)
    words = {_strip_marks(w) for w in _words(cleaned)}
    for term in _BILLING_TOPIC_TERMS:
        if term in _SHORT_TERMS_WORD_ONLY:
            # 짧은 일반어는 어절이 그 말로 시작할 때만 인정 (부분 일치 오탐 방지).
            if any(w.startswith(term) for w in words):
                return True
            continue
        if term in glued:
            return True
    return False


def _is_metric_only_question(question: str, words: list[str]) -> bool:
    """수치(횟수·기간·나이·비율·금액)만 묻고 대상이 빠진 짧은 질문인가.

    주제어가 없을 때만 의미가 있다 — 호출부에서 그 조건을 먼저 확인한다.
    """
    if len(words) > METRIC_ONLY_MAX_WORDS:
        return False
    return bool(_METRIC_RE.search(question))


def needs_clarification(question: str, *, has_known_topic: bool) -> bool:
    """이 질문은 혼자서 뜻이 통하지 않는 조각인가 → True 면 답하지 말고 되묻는다.

    ``has_known_topic``: vendor ``extract_procedures`` 가 행위를 하나라도 잡았는가.
    호출부가 그 결과를 그대로 넘긴다. 이 값이 False 여도 이 모듈의 주제 사전이
    보험청구 주제를 찾으면 "주제 있음" 으로 본다.
    """
    words = _words(question)
    if not words:
        # 빈 질문은 이 모듈이 판단할 몫이 아니다(입력 검증이 막는다).
        return False

    # 1) 지시어는 길이·주제보다 먼저 — 앞 대화 없이는 뜻이 정해지지 않는다.
    if has_anaphora(question):
        return True

    topic = has_known_topic or has_billing_topic(question)

    # 2) 수치만 묻는 맥락 의존 질문 (대상이 빠져 있다).
    if not topic and _is_metric_only_question(question, words):
        return True

    # 3) 주제가 잡히면 단독 검색이 가능하다.
    if topic:
        return False

    # 4) 주제가 없고 **내용어가 전혀 없는** 요청·확인 문장은 길이와 무관하게 조각이다.
    #    (3차 검수 P1-4 — 조사·어미를 붙여 3어절만 만들면 아래 길이 규칙이 무력화됐다)
    if _is_context_free_request(words):
        return True

    # 5) 주제 없는 1~2어절은 조각.
    if len(words) <= FRAGMENT_MAX_WORDS:
        return True

    # 6) 여기까지 왔다 = 보험청구 주제가 하나도 없는 질문이다 → 되묻는다 (2026-11-04).
    #
    #    예전에는 여기서 False(그대로 답변)였다. 그 결과 운영에서 "나는 검정색이 좋아"
    #    (3어절·주제 없음)에 챗봇이 "검정색 봉합사를 말하는 거라면 블랙실크가…" 라고
    #    답을 지어냈다. 3어절이라 5)의 2어절 기준을 한 끗 차이로 넘긴 것이다.
    #    어절 수로 선을 긋는 한 같은 구멍은 계속 생긴다.
    #
    #    **이 분기는 첫 질문에는 영향이 없다.** 호출부(`qa_service`)가 이전 대화가
    #    있을 때만 이 함수를 부른다. 즉 "대화 중인데 앞 대화와 이어지지도 않고
    #    보험청구 주제도 없는 입력" 에만 걸린다.
    #
    #    대가는 사전에 없는 어휘를 쓴 정상 질문도 되묻게 된다는 것이다. 운영 qa_logs
    #    최근 1,000건 실측으로 그 비용을 쟀다 — 사전 보강 전 50건(5.0%)이 새로
    #    막혔고, 위 사전·영문약어 보강 후 3건(0.3%)까지 내려갔다. 되묻기 오탐은
    #    "한 번 더 물어보는" 비용이고, 미탐은 "틀린 기준을 자신 있게 답하는" 비용이라
    #    이 교환을 택했다(사용자 결정, 2026-11-04).
    #
    #    오탐이 보고되면 고칠 곳은 이 분기가 아니라 `_BILLING_TOPIC_TERMS` 사전이다.
    return True
